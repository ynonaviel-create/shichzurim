-- ארכיון השחזורים — פתיחת מרחב השם shinunProg בטבלת user_kv
--
-- ── מה היה שבור ──────────────────────────────────────────────────
-- i❤️Shinun (app.js) מתייב כל דירוג לענן עם ns='shinunProg', אבל ה-check
-- המקורי ב-0001 הכיר בארבעה מרחבים בלבד. Postgres דחה כל upsert כזה, וזה
-- הרעיל את *כל* התור:
--
--   flush() אורז רצף set-ים רצופים לאותה בקשה, ועושה splice רק אחרי הצלחה.
--   שורת shinunProg אחת מפילה את כל האצווה — כולל progress ו-seen שנוסעים
--   איתה — והאצווה נשארת בראש תור ה-FIFO ומנסה שוב כל 10 שניות. לנצח.
--
-- כלומר: כל מי שנגע בשינון הפסיק לסנכרן *הכול*, בשקט, בלי הודעת שגיאה.
-- מקומית הכול נראה תקין (localStorage הוא מקור הקריאה), והנפילה מתגלה רק
-- כשמחליפים מכשיר — בדיוק התרחיש שבשבילו הענן נבנה.
--
-- ── התיקון ───────────────────────────────────────────────────────
-- להרחיב את ה-check. אין צורך במיגרציית נתונים: ה-upsert אידמפוטנטי, ולכן
-- ברגע שהאילוץ מתיר את המרחב — התורים התקועים אצל המשתמשים מתנקזים מעצמם
-- בפתיחה הבאה של האתר.
--
-- הוספתי גם את 'seenH' מראש (רשומת ההיסטוריה לכל שאלה). הוא עוד לא בשימוש,
-- אבל אילוץ שמתיר מרחב שטרם נכתב אינו מזיק — ואילוץ שחוסם מרחב שכן נכתב
-- משתיק את הענן של כולם. עדיף לשלם את המחיר בכיוון הזה.
--
-- להרצה: Supabase Dashboard → SQL Editor → הדבק והרץ.
-- לאימות שם האילוץ לפני ההרצה:  \d public.user_kv

alter table public.user_kv
  drop constraint if exists user_kv_ns_check;

alter table public.user_kv
  add constraint user_kv_ns_check
  check (ns in ('progress', 'seen', 'cardsRead', 'caseProg', 'shinunProg', 'seenH'));
